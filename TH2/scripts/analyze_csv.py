"""Analyze one TH02 CSV captured from Serial, verify MA5 and export figures.

Usage: python scripts/analyze_csv.py data/TH02-millis-SESSION.csv
Requires matplotlib for PNG output. No measurements are generated by this script.
"""
from __future__ import annotations
import argparse
import csv
import json
import math
import statistics
from collections import deque
from pathlib import Path


def read_samples(path):
    with Path(path).open(encoding="utf-8-sig", newline="") as stream:
        reader = csv.DictReader(stream)
        required = {"boot_id", "session_id", "mode", "seq", "t_ms", "dt_ms",
                    "temp_c", "rh_pct", "valid", "error", "temp_ma5", "rh_ma5"}
        if not reader.fieldnames or not required.issubset(reader.fieldnames):
            raise ValueError("Use a TH02 samples CSV from capture_serial.py; required columns are missing")
        rows = list(reader)
    if not rows:
        raise ValueError("CSV has no measurements")
    identities = {(r["boot_id"], r["session_id"], r["mode"]) for r in rows}
    if len(identities) != 1:
        raise ValueError("Analyze one boot/session/mode at a time; do not merge experiments")
    sequences = [int(r["seq"]) for r in rows]
    if any(b <= a for a, b in zip(sequences, sequences[1:])):
        raise ValueError("Sample sequence contains duplicates or is out of order")
    return rows


def analyze(rows, period_ms=3000):
    temp_window, rh_window = deque(maxlen=5), deque(maxlen=5)
    temperatures, humidities, temp_ma5, rh_ma5 = [], [], [], []
    mismatches, error_reasons, valid_count = [], {}, 0
    for row in rows:
        valid = row["valid"] == "1"
        if not valid:
            if row["temp_c"] or row["rh_pct"]:
                raise ValueError(f"Invalid sample {row['seq']} contains numeric sensor readings")
            reason = row["error"] or "unspecified"
            error_reasons[reason] = error_reasons.get(reason, 0) + 1
            t = h = filtered_t = filtered_h = math.nan
        else:
            t, h = float(row["temp_c"]), float(row["rh_pct"])
            if not math.isfinite(t) or not math.isfinite(h):
                raise ValueError(f"Valid sample {row['seq']} has a non-finite reading")
            valid_count += 1
            temp_window.append(t)
            rh_window.append(h)
            filtered_t = statistics.mean(temp_window) if len(temp_window) == 5 else math.nan
            filtered_h = statistics.mean(rh_window) if len(rh_window) == 5 else math.nan
        for key, expected in (("temp_ma5", filtered_t), ("rh_ma5", filtered_h)):
            cell = row[key].strip()
            try:
                observed = float(cell) if cell else math.nan
            except ValueError:
                observed = math.nan
            if (math.isnan(expected) and cell) or (
                math.isfinite(expected) and
                (not math.isfinite(observed) or abs(observed - expected) > 0.025)
            ):
                mismatches.append({"seq": int(row["seq"]), "column": key})
        temperatures.append(t)
        humidities.append(h)
        temp_ma5.append(filtered_t)
        rh_ma5.append(filtered_h)
    # Unsigned differences match the ESP32 time source, including millis wrap.
    gaps = [(int(b["t_ms"]) - int(a["t_ms"])) & 0xffffffff
            for a, b in zip(rows, rows[1:])]
    missing_seq = sum(int(b["seq"]) - int(a["seq"]) - 1 for a, b in zip(rows, rows[1:]))
    summary = {
        "source": "input CSV; verify provenance using experiment notes", "boot_id": rows[0]["boot_id"],
        "session_id": rows[0]["session_id"], "mode": rows[0]["mode"],
        "samples": len(rows), "valid": valid_count, "errors": len(rows) - valid_count,
        "error_reasons": error_reasons, "missing_sequence_numbers": missing_seq,
        "configured_period_ms": period_ms,
        "mean_interval_ms": statistics.mean(gaps) if gaps else None,
        "min_interval_ms": min(gaps) if gaps else None,
        "max_interval_ms": max(gaps) if gaps else None,
        "max_absolute_period_error_ms": max(abs(g - period_ms) for g in gaps) if gaps else None,
        "ma5_mismatches": mismatches,
        "note": "Intervals include sensor and LCD processing time; inspect experiment logs for causes."
    }
    # Unwrap the plotted time so a long uptime crossing millis wrap stays monotonic.
    elapsed = [0.0]
    for gap in gaps:
        elapsed.append(elapsed[-1] + gap / 1000)
    return summary, (elapsed, temperatures, humidities, temp_ma5, rh_ma5)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("csv_path", type=Path)
    parser.add_argument("--out-dir", type=Path, default=Path("figures"))
    parser.add_argument("--period-ms", type=int, default=3000)
    parser.add_argument("--summary-only", action="store_true")
    args = parser.parse_args()
    try:
        summary, series = analyze(read_samples(args.csv_path), args.period_ms)
    except (ValueError, KeyError) as exc:
        parser.error(str(exc))
    args.out_dir.mkdir(parents=True, exist_ok=True)
    summary_path = args.out_dir / f"{args.csv_path.stem}-summary.json"
    summary_path.write_text(json.dumps(summary, indent=2, ensure_ascii=False), encoding="utf-8")
    print(json.dumps(summary, indent=2, ensure_ascii=False))
    print(f"Saved: {summary_path}")
    if args.summary_only:
        return
    try:
        import matplotlib
        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
    except ImportError:
        raise SystemExit("Summary saved. Install plotting support: python -m pip install matplotlib")
    x, t, h, tm, hm = series
    for name, raw, filtered, unit in (("temperature", t, tm, "Temperature (°C)"),
                                      ("humidity", h, hm, "Humidity (%RH)")):
        fig, ax = plt.subplots(figsize=(10, 4.5), constrained_layout=True)
        ax.plot(x, raw, label="Raw", color="#677b93", marker=".", linewidth=1)
        ax.plot(x, filtered, label="MA5 (valid samples)", color="#008579", linewidth=2)
        ax.set(xlabel="Time since first sample (s)", ylabel=unit,
               title=f"TH02 / {summary['mode']} / {summary['session_id']}")
        ax.grid(alpha=0.2)
        ax.legend()
        output = args.out_dir / f"{args.csv_path.stem}-{name}.png"
        fig.savefig(output, dpi=180)
        plt.close(fig)
        print(f"Saved: {output}")


if __name__ == "__main__":
    main()
